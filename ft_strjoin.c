#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	size_t	len;
	char	*result;

	if (!s1 || !s2)
		return (NULL);
	if (ft_strlen(s1) > SIZE_MAX - ft_strlen(s2))
		return (NULL);
	len = ft_strlen(s1) + ft_strlen(s2);
	if (len == SIZE_MAX)
		return (NULL);
	result = malloc(len * sizeof(char) + 1);
	if (!result)
		return (NULL);
	ft_strlcpy(result, s1, len + 1);
	ft_strlcat(result, s2, len + 1);
	return (result);
}
